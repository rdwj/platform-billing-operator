package v1alpha1

import (
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

const (
	ConditionConsoleDeployed      = "Deployed"
	ConditionConsoleRouteAdmitted = "RouteAdmitted"

	AuthModeOpenShiftOAuth = "OpenShiftOAuth"
	AuthModeOIDC           = "OIDC"
	AuthModeBrokered       = "Brokered"
)

// ConsoleRouteConfig configures the OpenShift Route for the console.
type ConsoleRouteConfig struct {
	// Host is the desired hostname for the console Route.
	// Empty string means auto-generated by OpenShift.
	// +optional
	Host string `json:"host,omitempty"`

	// TLSSecretRef references a Secret containing TLS cert/key for the Route.
	// If unset, OpenShift generates a certificate.
	// +optional
	TLSSecretRef *corev1.LocalObjectReference `json:"tlsSecretRef,omitempty"`
}

// OIDCConfig configures OIDC authentication.
type OIDCConfig struct {
	// IssuerURL is the OIDC issuer URL.
	// +kubebuilder:validation:Required
	IssuerURL string `json:"issuerURL"`

	// ClientSecretRef references a Secret containing the OIDC client credentials.
	// +kubebuilder:validation:Required
	ClientSecretRef corev1.LocalObjectReference `json:"clientSecretRef"`

	// GroupsClaim is the JWT claim containing group memberships.
	// +optional
	// +kubebuilder:default="groups"
	GroupsClaim string `json:"groupsClaim,omitempty"`
}

// BrokerConfig configures brokered (federated IdP) authentication.
type BrokerConfig struct {
	// Deploy controls whether the operator deploys an embedded identity broker.
	// +optional
	Deploy bool `json:"deploy,omitempty"`

	// ExistingIssuerURL points to an externally managed identity broker.
	// +optional
	ExistingIssuerURL string `json:"existingIssuerURL,omitempty"`
}

// ConsoleRoles maps IdP groups to console roles.
type ConsoleRoles struct {
	// Admin groups have full access including walkthroughs and PriceBook editing.
	// +optional
	Admin []string `json:"admin,omitempty"`

	// Operator groups can manage tenants, dunning, and metering health.
	// +optional
	Operator []string `json:"operator,omitempty"`

	// Viewer groups have read-only access.
	// +optional
	Viewer []string `json:"viewer,omitempty"`
}

// ConsoleAuthConfig configures authentication for the console.
type ConsoleAuthConfig struct {
	// Mode selects the authentication mechanism.
	// +optional
	// +kubebuilder:validation:Enum=OpenShiftOAuth;OIDC;Brokered
	Mode string `json:"mode,omitempty"`

	// OIDC configures OIDC authentication.
	// +optional
	OIDC *OIDCConfig `json:"oidc,omitempty"`

	// Broker configures brokered (federated IdP) authentication.
	// +optional
	Broker *BrokerConfig `json:"broker,omitempty"`

	// Roles maps IdP groups to console roles.
	// +optional
	Roles *ConsoleRoles `json:"roles,omitempty"`
}

// TenantPortalConfig configures the tenant-facing portal.
type TenantPortalConfig struct {
	// Enabled controls whether the tenant portal is served at /portal.
	// +optional
	// +kubebuilder:default=true
	Enabled *bool `json:"enabled,omitempty"`
}

// BillingConsoleSpec defines the desired state of a BillingConsole.
type BillingConsoleSpec struct {
	// Enabled controls whether the console Deployment is created.
	// +optional
	// +kubebuilder:default=true
	Enabled *bool `json:"enabled,omitempty"`

	// Image is the console container image reference.
	// +optional
	// +kubebuilder:default="controller:latest"
	Image string `json:"image,omitempty"`

	// Replicas is the number of console pod replicas.
	// +optional
	// +kubebuilder:default=1
	Replicas *int32 `json:"replicas,omitempty"`

	// Route configures the OpenShift Route for the console.
	// +optional
	Route *ConsoleRouteConfig `json:"route,omitempty"`

	// Auth configures authentication for the console.
	// +optional
	Auth *ConsoleAuthConfig `json:"auth,omitempty"`

	// TenantPortal configures the tenant-facing portal.
	// +optional
	TenantPortal *TenantPortalConfig `json:"tenantPortal,omitempty"`
}

// BillingConsoleStatus defines the observed state of a BillingConsole.
type BillingConsoleStatus struct {
	// URL is the externally reachable URL of the console.
	// +optional
	URL string `json:"url,omitempty"`

	// Conditions represent the latest available observations.
	// +optional
	// +patchMergeKey=type
	// +patchStrategy=merge
	// +listType=map
	// +listMapKey=type
	Conditions []metav1.Condition `json:"conditions,omitempty" patchStrategy:"merge" patchMergeKey:"type"`

	// ObservedGeneration is the most recent generation observed by the controller.
	// +optional
	ObservedGeneration int64 `json:"observedGeneration,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:scope=Cluster
// +kubebuilder:printcolumn:name="URL",type=string,JSONPath=".status.url"
// +kubebuilder:printcolumn:name="Deployed",type=string,JSONPath=`.status.conditions[?(@.type=="Deployed")].status`
// +kubebuilder:printcolumn:name="Age",type=date,JSONPath=".metadata.creationTimestamp"

// BillingConsole is the Schema for the billingconsoles API.
// It configures operator-managed deployment of the billing console UI.
// Cluster-scoped; the controller enforces singleton semantics (name: default).
type BillingConsole struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   BillingConsoleSpec   `json:"spec,omitempty"`
	Status BillingConsoleStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true

// BillingConsoleList contains a list of BillingConsole resources.
type BillingConsoleList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []BillingConsole `json:"items"`
}

func init() {
	SchemeBuilder.Register(&BillingConsole{}, &BillingConsoleList{})
}
